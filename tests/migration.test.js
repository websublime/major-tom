test('--quarantine never overwrites a destination that already exists', (t) => {
  const repo = onboardedProject()
  t.after(() => remove(repo))

  write(repo, '.claude/server/dashboard-server.js', RETIRED_DASHBOARD_SERVER)
  // Whatever is already sitting at the destination is the user's, whether they put it there
  // or an earlier run did. Overwriting it would destroy it, which is the act D55 forbids
  // under any name.
  const occupant = '// the user kept notes in this file\n'
  write(repo, '.claude/server/dashboard-server.js' + RETIRED_SUFFIX, occupant)

  const before = treeDigest(repo)
  const result = run(['--quarantine', repo])

  assert.equal(result.status, 0, 'a refusal to overwrite is a report, not a failure')
  assert.equal(treeDigest(repo), before, 'neither the residue nor the occupant may change')
  // Stated on its own rather than left to the digest, because this is the property the whole
  // decision rests on: not merely that no rename happened, but that the bytes already sitting
  // at the destination are the bytes still sitting there afterwards.
  assert.equal(
    fs.readFileSync(path.join(repo, '.claude', 'server', 'dashboard-server.js' + RETIRED_SUFFIX), 'utf8'),
    occupant,
    'the file already at the destination must survive byte for byte'
  )
  assert.equal(
    fs.readFileSync(path.join(repo, '.claude', 'server', 'dashboard-server.js'), 'utf8'),
    RETIRED_DASHBOARD_SERVER,
    'and the residue must still be there, under its original name, byte for byte'
  )
  assert.equal(lineFor(result.stdout, 'SKIPPED', '.claude/server/dashboard-server.js').length, 1, result.all)
  assert.match(result.stdout, /already exists; nothing is ever overwritten/)
  assert.match(result.stdout, /quarantine: 0 quarantined, 1 skipped, 0 failed/)
})

test('--quarantine reports a real I/O failure, exits non-zero, and leaves the residue intact', (t) => {
  // The only path in this feature that can abort an onboard, so it is the one that most needs
  // a test rather than a reading. The failure is produced by the filesystem, not by a stub:
  // a directory the process may read and traverse but not write cannot be renamed within, so
  // renameSync raises EACCES exactly as it would on a read-only checkout or a locked volume.
  //
  // Root ignores those permission bits. Under root the rename would succeed, this test would
  // pass, and it would have proved nothing at all, which is worse than not having it, so it
  // says why it did not run rather than reporting a pass it did not earn.
  if (typeof process.getuid === 'function' && process.getuid() === 0) {
    t.skip('running as root: the directory permission bits this test depends on are not enforced for root, so the rename would succeed and the test would pass without exercising the failure path')
    return
  }

  const repo = onboardedProject()
  const dir = path.join(repo, '.claude', 'server')
  // Restoring the mode is registered before the directory is ever made unwritable, and it runs
  // whether the test passes or throws. A failing assertion must not leave an undeletable
  // directory behind in os.tmpdir(): remove() cannot unlink the files inside a 0555 directory,
  // so the chmod has to come first here and it has to be unconditional.
  t.after(() => {
    try {
      fs.chmodSync(dir, 0o755)
    } catch (err) {
      // Already restored, or the directory is gone. Either way there is nothing left to fix,
      // and throwing from a cleanup would hide whatever the test itself reported.
    }
    remove(repo)
  })

  const residue = path.join(dir, 'dashboard-server.js')
  write(repo, '.claude/server/dashboard-server.js', RETIRED_DASHBOARD_SERVER)
  fs.chmodSync(dir, 0o555)

  const result = run(['--quarantine', repo])

  const failedLines = result.stderr.split('\n').filter((line) => line.startsWith('FAILED '))
  assert.equal(failedLines.length, 1, 'one failure, one line\n' + result.all)
  assert.match(failedLines[0], /\.claude\/server\/dashboard-server\.js/, 'the line must name the path it could not move')
  assert.match(failedLines[0], /EACCES/, 'and must carry what the filesystem actually said, not a paraphrase')

  assert.notEqual(result.status, 0, 'a mode that did not do what it said it did must fail')
  assert.match(result.stdout, /quarantine: 0 quarantined, 0 skipped, 1 failed/, result.all)

  // The point of the whole design: when the move cannot happen, the file is exactly as it was.
  assert.equal(fs.existsSync(residue), true, 'the residue must still be there')
  assert.equal(fs.readFileSync(residue, 'utf8'), RETIRED_DASHBOARD_SERVER, 'under its original name, byte for byte')
  assert.equal(fs.existsSync(residue + RETIRED_SUFFIX), false, 'and nothing may have been created at the destination')
})

