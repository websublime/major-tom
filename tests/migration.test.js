// The template above is what the plugin shipped; what landed in a target repository was that
// template with the data island filled in, because `render.js inject` replaced the island
// content and left every other byte alone. The regex is the one the retired inject used, so
// the fixture is produced the way the artifact was produced rather than typed out as
// somebody's idea of the result.
function injectIsland(html, data) {
  const island = /(<script[^>]*id="major-tom-data"[^>]*>)[\s\S]*?(<\/script>)/
  assert.ok(island.test(html), 'the historic template must carry the island inject anchored on')
  return html.replace(island, '$1\n' + JSON.stringify(data) + '\n$2')
}

// What an onboard of that era actually wrote into <persistence.root>/dashboard.html.
function retiredDashboardArtifact() {
  return injectIsland(RETIRED_DASHBOARD_TEMPLATE, { project: { name: 'fixture' }, generatedAt: '2026-08-06T10:00:00Z' })
}

